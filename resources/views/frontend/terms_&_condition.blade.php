<script>
    const tabs = document.querySelectorAll('.nav-link');

    tabs.forEach(tab => {
        tab.addEventListener('click', function() {
            const tabName = this.textContent.trim().replace(/\s+/g, '_').toLowerCase();
            history.pushState(null, null, tabName);
        });
    });

    // Handle initial page load with a specific tab
    const initialTabName = window.location.pathname.substring(1);
    if (initialTabName) {
        const initialTab = document.querySelector(`[aria-controls="${initialTabName}"]`);
        if (initialTab) {
            initialTab.click();
        }
    }
</script>




